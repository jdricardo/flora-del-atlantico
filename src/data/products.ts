/**
 * Elige los cuidados de un producto.
 *
 * Solo "arreglos en caja y base" necesita mirar más allá de la categoría: las
 * referencias `b*` del catálogo impreso son las bases de vidrio y taza, que
 * llegan en agua; las cajas, canastas y materas van sobre espuma floral y se
 * arruinan si el cliente les cambia el agua que no tienen.
 */
function cuidadosDe(seed: ProductSeed): string[] {
  if (seed.care) return seed.care;
  if (seed.category === 'arreglos-caja-base' && seed.id.startsWith('b')) {
    return CUIDADOS_EN_AGUA;
  }
  return CARE_BY_CATEGORY[seed.category];
}

